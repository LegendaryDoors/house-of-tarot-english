TOP_MARGIN = 2                      # glyph row 0 lands on cell row 2
SPACE_WIDTH = 4
ALPHABET = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
            ".,'\"!?:;-()/&*+%")
assert set(ALPHABET) <= set(F), set(ALPHABET) - set(F)

# code assignment: 0 end, 1 newline, 2 space, then ALPHABET from 3 skipping 8 and 9
CODE_OF: dict[str, int] = {" ": 2}
_c = 3
for ch in ALPHABET:
    if _c in (8, 9):
        _c = 10
    CODE_OF[ch] = _c
    _c += 1
MAX_CODE = _c - 1                   # last English code
CHAR_OF = {v: k for k, v in CODE_OF.items()}


def rows_of(ch: str) -> list[str]:
    """The glyph's rows with any blank columns on the left trimmed away, so every glyph's
    ink starts at column 0 and line starts are flush (I, J, i, j, l, 1, f, t were centred)."""
    rows = F[ch]
    inked = [r for r in rows if r.strip()]
    if not inked:
        return rows
    lead = min(len(r) - len(r.lstrip()) for r in inked)
    return [r[lead:] for r in rows]


def glyph_width(ch: str) -> int:
    if ch == " ":
        return SPACE_WIDTH
    rows = rows_of(ch)
    w = max(len(r.rstrip()) for r in rows) if any(r.strip() for r in rows) else 3
    return w + 1                    # one blank column of spacing


WIDTH_OF: dict[str, int] = {ch: glyph_width(ch) for ch in CODE_OF}


def cell_bytes(ch: str) -> bytes:
    """16x16 1bpp row-major (2 bytes per row, MSB = left pixel)."""
    rows = [0] * 16
    if ch != " ":
        for r, row in enumerate(rows_of(ch)):
            bits = 0
            for x, px in enumerate(row):
                if px == "#":
                    bits |= 1 << (15 - x)
            rows[r + TOP_MARGIN] = bits
    return b"".join(bytes([(v >> 8) & 0xFF, v & 0xFF]) for v in rows)


def text_width(s: str) -> int:
    return sum(WIDTH_OF[ch] for ch in s)


